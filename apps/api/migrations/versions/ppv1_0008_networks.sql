	CONSTRAINT ck_net_locations_manual_poverty_rate CHECK (manual_poverty_rate IS NULL OR manual_poverty_rate BETWEEN 0 AND 1), 
	CONSTRAINT ck_net_locations_manual_snap_rate CHECK (manual_snap_rate IS NULL OR manual_snap_rate BETWEEN 0 AND 1), 
	CONSTRAINT ck_net_locations_acs_provenance CHECK ((poverty_rate IS NULL AND snap_rate IS NULL) OR (acs_source IS NOT NULL AND acs_year IS NOT NULL AND acs_fetched_at IS NOT NULL)), 
	CONSTRAINT ck_net_locations_exclusion_reason CHECK (NOT excluded OR exclusion_reason IS NOT NULL), 
	CONSTRAINT fk_net_locations_organization_id_organizations FOREIGN KEY(organization_id) REFERENCES organizations (id) ON DELETE RESTRICT, 
	CONSTRAINT uq_net_locations_organization_id_id UNIQUE (organization_id, id)
);
