CREATE TABLE planning_plans (
	scenario_id UUID NOT NULL,
	job_id UUID NOT NULL,
	attempt_id UUID NOT NULL,
	comparison_id UUID,
	method TEXT NOT NULL,
	settings JSONB NOT NULL,
	result JSONB NOT NULL,
	result_hash VARCHAR(64) NOT NULL,
	organization_id UUID NOT NULL,
	id UUID NOT NULL,
	recorded_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp() NOT NULL,
	CONSTRAINT pk_planning_plans PRIMARY KEY (id),
	CONSTRAINT fk_planning_plans_organization_id_scenario_id_planning__47c5 FOREIGN KEY(organization_id, scenario_id) REFERENCES planning_scenarios (organization_id, id) ON DELETE RESTRICT,
	CONSTRAINT fk_planning_plans_organization_id_comparison_id_plannin_9e10 FOREIGN KEY(organization_id, comparison_id) REFERENCES planning_comparisons (organization_id, id) ON DELETE RESTRICT,
	CONSTRAINT fk_planning_plans_organization_id_job_id_compute_jobs FOREIGN KEY(organization_id, job_id) REFERENCES compute_jobs (organization_id, job_id) ON DELETE RESTRICT,
	CONSTRAINT fk_planning_plans_organization_id_attempt_id_compute_attempts FOREIGN KEY(organization_id, attempt_id) REFERENCES compute_attempts (organization_id, attempt_id) ON DELETE RESTRICT,
	CONSTRAINT fk_planning_plans_job_id_attempt_id_compute_attempts FOREIGN KEY(job_id, attempt_id) REFERENCES compute_attempts (job_id, attempt_id) ON DELETE RESTRICT,
	CONSTRAINT uq_planning_plans_attempt_id_method UNIQUE (attempt_id, method),
	CONSTRAINT ck_planning_plans_method CHECK (method IN ('CLASSICAL_GP', 'EGP_PI_INSPIRED')),
	CONSTRAINT ck_planning_plans_hash CHECK (result_hash ~ '^[0-9a-f]{64}$'),
	CONSTRAINT ck_planning_plans_verified CHECK (result->>'outcome' = 'VERIFIED' AND result->'verification'->>'passed' = 'true'),
	CONSTRAINT fk_planning_plans_organization_id_organizations FOREIGN KEY(organization_id) REFERENCES organizations (id) ON DELETE RESTRICT,
	CONSTRAINT uq_planning_plans_organization_id_id UNIQUE (organization_id, id)
);
CREATE TABLE planning_reviews (
	plan_id UUID NOT NULL,
	actor VARCHAR(200) NOT NULL,
	action TEXT NOT NULL,
	result_hash VARCHAR(64) NOT NULL,
	note VARCHAR(2000),
	organization_id UUID NOT NULL,
	id UUID NOT NULL,
	recorded_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp() NOT NULL,
	CONSTRAINT pk_planning_reviews PRIMARY KEY (id),
	CONSTRAINT fk_planning_reviews_organization_id_plan_id_planning_plans FOREIGN KEY(organization_id, plan_id) REFERENCES planning_plans (organization_id, id) ON DELETE RESTRICT,
	CONSTRAINT ck_planning_reviews_action CHECK (action IN ('REVIEWED', 'REJECTED')),
	CONSTRAINT ck_planning_reviews_hash CHECK (result_hash ~ '^[0-9a-f]{64}$'),
	CONSTRAINT fk_planning_reviews_organization_id_organizations FOREIGN KEY(organization_id) REFERENCES organizations (id) ON DELETE RESTRICT,
	CONSTRAINT uq_planning_reviews_organization_id_id UNIQUE (organization_id, id)
);
