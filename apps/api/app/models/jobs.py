"""Jobs-only physical schema (WQ-02). Revision 0001 is the authority for constraints and
triggers; this metadata mirrors its columns so drift is tested, not autogenerated."""

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    Integer,
    MetaData,
    Table,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, TIMESTAMP, UUID

metadata = MetaData()

TZ = TIMESTAMP(timezone=True)

compute_control = Table(
    "compute_control",
    metadata,
    Column("lane_id", Text, primary_key=True),
    Column("supervisor_id", UUID(as_uuid=True)),
    Column("generation", BigInteger, nullable=False),
    Column("host_identity", Text),
    Column("state", Text, nullable=False),
    Column("heartbeat_at", TZ),
    Column("active_attempt_id", UUID(as_uuid=True)),
    Column("recovery_required", Boolean, nullable=False),
    Column("effective_limits", JSONB, nullable=False),
    Column("updated_at", TZ, nullable=False),
)

compute_jobs = Table(
    "compute_jobs",
    metadata,
    Column("job_id", UUID(as_uuid=True), primary_key=True),
    Column("lane_id", Text, nullable=False),
    Column("organization_id", UUID(as_uuid=True), nullable=False),
    Column("requested_by_ref", Text, nullable=False),
    Column("operation_kind", Text, nullable=False),
    Column("handler_contract", Text, nullable=False),
    Column("input_schema_version", Text, nullable=False),
    Column("input_package", JSONB, nullable=False),
    Column("input_sha256", Text, nullable=False),
    Column("current_attempt_id", UUID(as_uuid=True), nullable=False),
    Column("state", Text, nullable=False),
    Column("created_at", TZ, nullable=False),
    Column("updated_at", TZ, nullable=False),
)

compute_attempts = Table(
    "compute_attempts",
    metadata,
    Column("attempt_id", UUID(as_uuid=True), primary_key=True),
    Column("job_id", UUID(as_uuid=True), nullable=False),
    Column("attempt_number", Integer, nullable=False),
    Column("lane_id", Text, nullable=False),
    Column("organization_id", UUID(as_uuid=True), nullable=False),
    Column("state", Text, nullable=False),
    Column("reason_code", Text),
    Column("state_version", BigInteger, nullable=False),
    Column("enqueued_at", TZ, nullable=False),
    Column("queue_deadline_at", TZ, nullable=False),
    Column("supervisor_id", UUID(as_uuid=True)),
    Column("supervisor_generation", BigInteger),
    Column("execution_token", UUID(as_uuid=True)),
    Column("started_at", TZ),
    Column("execution_deadline_at", TZ),
    Column("primary_deadline_at", TZ),
    Column("current_phase", Text),
    Column("execution_boundary", JSONB),
    Column("stop_requested_at", TZ),
    Column("stop_reason", Text),
    Column("cleanup_confirmed_at", TZ),
    Column("diagnostics", JSONB, nullable=False),
    Column("completed_at", TZ),
    Column("result_manifest", JSONB),
    Column("error", JSONB),
)

compute_commands = Table(
    "compute_commands",
    metadata,
    Column("command_id", UUID(as_uuid=True), primary_key=True),
    Column("organization_id", UUID(as_uuid=True), nullable=False),
    Column("action", Text, nullable=False),
    Column("idempotency_key", Text, nullable=False),
    Column("request_sha256", Text, nullable=False),
    Column("job_id", UUID(as_uuid=True), nullable=False),
    Column("attempt_id", UUID(as_uuid=True)),
    Column("response", JSONB, nullable=False),
    Column("created_at", TZ, nullable=False),
)

compute_audit_events = Table(
    "compute_audit_events",
    metadata,
    Column("event_id", BigInteger, primary_key=True),
    Column("occurred_at", TZ, nullable=False),
    Column("lane_id", Text, nullable=False),
    Column("job_id", UUID(as_uuid=True)),
    Column("attempt_id", UUID(as_uuid=True)),
    Column("event_type", Text, nullable=False),
    Column("from_state", Text),
    Column("to_state", Text),
    Column("supervisor_id", UUID(as_uuid=True)),
    Column("supervisor_generation", BigInteger),
    Column("reason_code", Text),
    Column("details", JSONB, nullable=False),
)
